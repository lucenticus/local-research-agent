"""Общие фикстуры pytest.

Пока здесь одна задача: не дать тестам писать в настоящее состояние на диске.
"""

from __future__ import annotations

import pytest

from src import config


@pytest.fixture(autouse=True)
def isolated_citation_cache(tmp_path, monkeypatch):
    """Кэш цитируемости — во временную папку, для КАЖДОГО теста.

    Autouse, потому что забыть его подключить — значит получить два разных
    сорта неприятностей сразу, и оба поймались на первом же прогоне:

    1. тесты писали `.cache/citations.json` в рабочую копию репозитория;
    2. значение, записанное одним тестом, всплывало в другом — тест на 429
       переставал видеть 429, потому что число уже лежало в кэше от
       соседнего теста. Тест зелёный, поведение непроверенное.

    Изоляция по умолчанию надёжнее дисциплины: новому тесту не нужно знать
    про существование кэша, чтобы не пострадать от него.
    """
    monkeypatch.setattr(config, "CITATION_CACHE_PATH", tmp_path / "citations.json")
